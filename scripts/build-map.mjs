#!/usr/bin/env node
//  build-map.mjs: bundle ui-src/map/ into the served map.js.
//
//  map.js is the map editor for geojson pages (Leaflet, lattice's own
//  drawing tools and its page core), loaded lazily when a map page opens.
//  It goes through esbuild like sheet.js: one minified IIFE, no source
//  map, nothing global but window.LatMap. It bundles three packages,
//  pinned exact in scripts/package.json and installed with npm ci
//  --ignore-scripts: leaflet (its ESM build, which sets no global L, and
//  its CSS as text), mgrs and @tmcw/togeojson.
//
//  The build writes ui-src/map/vendor/LICENSES from the packages that
//  actually went into the bundle, and puts the same notices at the top of
//  map.js. CI rebuilds and diffs both, so the output must be
//  byte-identical run to run.
//
//  It fails on a bundled package whose licence is not MIT, ISC or BSD, or
//  that is not pinned exact in scripts/package.json. And it fails when
//  map.js is over its budget: 240 KB raw, 72 KB gzipped.
//  Leaflet alone is about 150 KB of it, and none of Leaflet shakes out.
//
//  Usage: node scripts/build-map.mjs [--quiet]
import { build, transform } from 'esbuild';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { gzipSync } from 'zlib';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const srcDir = join(root, 'ui-src', 'map');
const out = join(root, 'code', 'nex', 'lattice', 'ui-app', 'map.js');
const licences = join(srcDir, 'vendor', 'LICENSES');

export const BUDGET = { raw: 240 * 1024, gzip: 72 * 1024 };

const r = await build({
  entryPoints: [join(srcDir, 'index.js')],
  absWorkingDir: root,
  nodePaths: [join(here, 'node_modules')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  charset: 'utf8',
  //  leaflet.css, minified and injected once by view.js as text
  plugins: [{
    name: 'css-text',
    setup(b) {
      b.onLoad({ filter: /\.css$/ }, async (a) => {
        const css = (await transform(readFileSync(a.path, 'utf8'), { loader: 'css', minify: true })).code;
        return { contents: 'export default ' + JSON.stringify(css.trim()) + ';', loader: 'js' };
      });
    },
  }],
  metafile: true,
  write: false,
  logLevel: 'warning',
});

//  the packages esbuild actually pulled in, from the input paths
const pkgs = new Map();
for (const p of Object.keys(r.metafile.inputs)) {
  const m = p.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (!m || pkgs.has(m[1])) continue;
  const dir = join(here, 'node_modules', m[1]);
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  let text = '';
  for (const f of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'license.md', 'license']) {
    try { text = readFileSync(join(dir, f), 'utf8'); break; } catch { /* next */ }
  }
  if (!text) { console.error(`build-map: ${m[1]} has no LICENSE file`); process.exit(1); }
  pkgs.set(m[1], { name: m[1], version: pj.version, license: pj.license, text });
}
const list = [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name));

//  the licence gate: every bundled package carries a licence lattice may
//  bundle with its notices (lattice is PolyForm Noncommercial, so no GPL,
//  AGPL or LGPL), and is pinned exact in scripts/package.json
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause']);
const pins = JSON.parse(readFileSync(join(here, 'package.json'), 'utf8')).devDependencies || {};
for (const p of list) {
  if (!ALLOWED.has(p.license)) { console.error(`build-map: ${p.name} is ${p.license}, which map.js may not bundle`); process.exit(1); }
  if (pins[p.name] !== p.version) { console.error(`build-map: ${p.name} is not pinned exact at ${p.version} in scripts/package.json`); process.exit(1); }
}

//  one copy of each licence body, with every package and copyright line
//  that carries it
const bodies = new Map();
for (const p of list) {
  const lines = p.text.replace(/\r/g, '').trim().split('\n');
  const copy = lines.filter((l) => /^\s*copyright\b/i.test(l)).map((l) => l.trim());
  const body = lines.filter((l) => !/^\s*copyright\b/i.test(l)).join('\n').trim();
  if (!bodies.has(body)) bodies.set(body, { pkgs: [], copy: new Set() });
  const b = bodies.get(body);
  b.pkgs.push(`${p.name}@${p.version} (${p.license})`);
  copy.forEach((c) => b.copy.add(c));
}
const notices = [...bodies.entries()].map(([body, b]) =>
  b.pkgs.join('\n') + '\n\n' + [...b.copy].sort().join('\n') + '\n\n' + body).join('\n\n----\n\n');

writeFileSync(licences,
  'Third-party code bundled into code/nex/lattice/ui-app/map.js.\n'
  + 'Generated by scripts/build-map.mjs from the installed packages. Do not edit.\n\n'
  + notices + '\n');

const banner = '/* BUILT FILE, do not edit. Source: ui-src/map/, build: scripts/build-map.mjs\n\n'
  + 'Bundles third-party code under these licences:\n\n'
  + notices.replace(/\*\//g, '* /') + '\n*/\n';
const js = banner + r.outputFiles[0].text;
writeFileSync(out, js);

const raw = Buffer.byteLength(js);
const gz = gzipSync(js, { level: 9 }).length;
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
if (!process.argv.includes('--quiet')) {
  console.log(`built map.js: ${kb(raw)} raw, ${kb(gz)} gzipped `
    + `(budget ${kb(BUDGET.raw)} / ${kb(BUDGET.gzip)}), ${list.length} packages`);
}
if (raw > BUDGET.raw || gz > BUDGET.gzip) {
  console.error(`build-map: map.js is over budget: ${kb(raw)} raw, ${kb(gz)} gzipped`);
  process.exit(1);
}
