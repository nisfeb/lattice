#!/usr/bin/env node
//  build-sheet.mjs: bundle ui-src/sheet/ into the served sheet.js.
//
//  sheet.js is the spreadsheet editor (the grid, lattice's flat ODS core
//  and its formula engine), loaded lazily when a fods page opens. It goes
//  through esbuild like writer.js: one minified IIFE, no source map,
//  nothing global but window.LatSheet. It shares the Writer core's XML
//  tokenizer and its zip packer (ui-src/writer/xml.js, odt.js), and so
//  bundles the one package the packer needs, tiny-inflate, pinned exact in
//  scripts/package.json and installed with npm ci --ignore-scripts.
//
//  The build writes ui-src/sheet/vendor/LICENSES from the packages that
//  actually went into the bundle, and puts the same notices at the top of
//  sheet.js. CI rebuilds and diffs both, so the output must be
//  byte-identical run to run.
//
//  It fails when sheet.js is over its budget: 200 KB raw, 70 KB gzipped.
//
//  Usage: node scripts/build-sheet.mjs [--quiet]
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { gzipSync } from 'zlib';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const srcDir = join(root, 'ui-src', 'sheet');
const out = join(root, 'code', 'nex', 'lattice', 'ui-app', 'sheet.js');
const licences = join(srcDir, 'vendor', 'LICENSES');

export const BUDGET = { raw: 200 * 1024, gzip: 70 * 1024 };

const r = await build({
  entryPoints: [join(srcDir, 'index.js')],
  absWorkingDir: root,
  nodePaths: [join(here, 'node_modules')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  charset: 'utf8',
  //  ui-src/sheet/blank.fods, the new-page template, inlined as a string
  loader: { '.fods': 'text' },
  metafile: true,
  write: false,
  logLevel: 'warning',
});

//  the packages esbuild actually pulled in, from the input paths
const pkgs = new Map();
for (const p of Object.keys(r.metafile.inputs)) {
  const m = p.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (!m || pkgs.has(m[1])) continue;
  const dir = join(here, 'node_modules', m[1]);
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  let text = '';
  for (const f of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE']) {
    try { text = readFileSync(join(dir, f), 'utf8'); break; } catch { /* next */ }
  }
  if (!text) { console.error(`build-sheet: ${m[1]} has no LICENSE file`); process.exit(1); }
  pkgs.set(m[1], { name: m[1], version: pj.version, license: pj.license, text });
}
const list = [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name));

//  one copy of each licence body, with every package and copyright line
//  that carries it
const bodies = new Map();
for (const p of list) {
  const lines = p.text.replace(/\r/g, '').trim().split('\n');
  const copy = lines.filter((l) => /^\s*copyright\b/i.test(l)).map((l) => l.trim());
  const body = lines.filter((l) => !/^\s*copyright\b/i.test(l)).join('\n').trim();
  if (!bodies.has(body)) bodies.set(body, { pkgs: [], copy: new Set() });
  const b = bodies.get(body);
  b.pkgs.push(`${p.name}@${p.version} (${p.license})`);
  copy.forEach((c) => b.copy.add(c));
}
const notices = [...bodies.entries()].map(([body, b]) =>
  b.pkgs.join('\n') + '\n\n' + [...b.copy].sort().join('\n') + '\n\n' + body).join('\n\n----\n\n');

writeFileSync(licences,
  'Third-party code bundled into code/nex/lattice/ui-app/sheet.js.\n'
  + 'Generated by scripts/build-sheet.mjs from the installed packages. Do not edit.\n\n'
  + notices + '\n');

const banner = '/* BUILT FILE, do not edit. Source: ui-src/sheet/, build: scripts/build-sheet.mjs\n\n'
  + 'Bundles third-party code under these licences:\n\n'
  + notices.replace(/\*\//g, '* /') + '\n*/\n';
const js = banner + r.outputFiles[0].text;
writeFileSync(out, js);

const raw = Buffer.byteLength(js);
const gz = gzipSync(js, { level: 9 }).length;
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
if (!process.argv.includes('--quiet')) {
  console.log(`built sheet.js: ${kb(raw)} raw, ${kb(gz)} gzipped `
    + `(budget ${kb(BUDGET.raw)} / ${kb(BUDGET.gzip)}), ${list.length} packages`);
}
if (raw > BUDGET.raw || gz > BUDGET.gzip) {
  console.error(`build-sheet: sheet.js is over budget: ${kb(raw)} raw, ${kb(gz)} gzipped`);
  process.exit(1);
}
