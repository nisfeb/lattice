#!/usr/bin/env node
//  build-writer.mjs: bundle ui-src/writer/ into the served writer.js.
//
//  writer.js is the Writer editor (ProseMirror plus lattice's flat ODT
//  core), loaded lazily when a fodt page opens. It is the one client asset
//  with runtime dependencies, so unlike app.js it goes through a bundler:
//  esbuild, one minified IIFE, no source map, nothing global but
//  window.LatWriter. The ProseMirror packages are pinned exact in
//  scripts/package.json and installed with npm ci --ignore-scripts.
//
//  The build also writes ui-src/writer/vendor/LICENSES from the packages
//  that actually went into the bundle, and puts the same notices at the top
//  of writer.js, so the MIT notices travel with the file. CI rebuilds and
//  diffs both, so the output must be byte-identical run to run.
//
//  It fails when writer.js is over the phase 1 budget (spec, Bundle and
//  lazy loading): 400 KB raw, 130 KB gzipped.
//
//  Usage: node scripts/build-writer.mjs [--quiet]
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { gzipSync } from 'zlib';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const srcDir = join(root, 'ui-src', 'writer');
const out = join(root, 'code', 'nex', 'lattice', 'ui-app', 'writer.js');
const licences = join(srcDir, 'vendor', 'LICENSES');

export const BUDGET = { raw: 400 * 1024, gzip: 130 * 1024 };

const r = await build({
  entryPoints: [join(srcDir, 'index.js')],
  absWorkingDir: root,
  nodePaths: [join(here, 'node_modules')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  charset: 'utf8',
  metafile: true,
  write: false,
  logLevel: 'warning',
});

//  the packages esbuild actually pulled in, from the input paths
const pkgs = new Map();
for (const p of Object.keys(r.metafile.inputs)) {
  const m = p.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (!m || pkgs.has(m[1])) continue;
  const dir = join(here, 'node_modules', m[1]);
  const pj = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  let text = '';
  for (const f of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE']) {
    try { text = readFileSync(join(dir, f), 'utf8'); break; } catch { /* next */ }
  }
  if (!text) { console.error(`build-writer: ${m[1]} has no LICENSE file`); process.exit(1); }
  pkgs.set(m[1], { name: m[1], version: pj.version, license: pj.license, text });
}
const list = [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name));

//  one copy of each licence body, with every package and copyright line
//  that carries it
const bodies = new Map();
for (const p of list) {
  const lines = p.text.replace(/\r/g, '').trim().split('\n');
  const copy = lines.filter((l) => /^\s*copyright\b/i.test(l)).map((l) => l.trim());
  const body = lines.filter((l) => !/^\s*copyright\b/i.test(l)).join('\n').trim();
  if (!bodies.has(body)) bodies.set(body, { pkgs: [], copy: new Set() });
  const b = bodies.get(body);
  b.pkgs.push(`${p.name}@${p.version} (${p.license})`);
  copy.forEach((c) => b.copy.add(c));
}
const notices = [...bodies.entries()].map(([body, b]) =>
  b.pkgs.join('\n') + '\n\n' + [...b.copy].sort().join('\n') + '\n\n' + body).join('\n\n----\n\n');

writeFileSync(licences,
  'Third-party code bundled into code/nex/lattice/ui-app/writer.js.\n'
  + 'Generated by scripts/build-writer.mjs from the installed packages. Do not edit.\n\n'
  + notices + '\n');

const banner = '/* BUILT FILE, do not edit. Source: ui-src/writer/, build: scripts/build-writer.mjs\n\n'
  + 'Bundles third-party code under these licences:\n\n'
  + notices.replace(/\*\//g, '* /') + '\n*/\n';
const js = banner + r.outputFiles[0].text;
writeFileSync(out, js);

const raw = Buffer.byteLength(js);
const gz = gzipSync(js, { level: 9 }).length;
const kb = (n) => (n / 1024).toFixed(1) + ' KB';
if (!process.argv.includes('--quiet')) {
  console.log(`built writer.js: ${kb(raw)} raw, ${kb(gz)} gzipped `
    + `(budget ${kb(BUDGET.raw)} / ${kb(BUDGET.gzip)}), ${list.length} packages`);
}
if (raw > BUDGET.raw || gz > BUDGET.gzip) {
  console.error(`build-writer: writer.js is over budget: ${kb(raw)} raw, ${kb(gz)} gzipped`);
  process.exit(1);
}
